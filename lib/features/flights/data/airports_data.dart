class AirportInfo {
  final String code; // IATA code (e.g. ALG)
  final String city;
  final String name;
  final String country;
  final String region;
  final bool isPopular;
  final String cityAr;
  final String nameAr;
  final String countryAr;
  final String flag;

  const AirportInfo({
    required this.code,
    required this.city,
    required this.name,
    required this.country,
    required this.region,
    this.isPopular = false,
    this.cityAr = '',
    this.nameAr = '',
    this.countryAr = '',
    this.flag = '✈️',
  });

  static String _normalizeArabic(String text) {
    return text
        .replaceAll(RegExp(r'[\u064B-\u0652]'), '') // remove tashkeel
        .replaceAll(RegExp(r'[إأآ]'), 'ا')
        .replaceAll('ة', 'ه')
        .replaceAll('ى', 'ي');
  }

  bool matches(String query) {
    final raw = query.trim().toLowerCase();
    if (raw.isEmpty) return true;

    final normQuery = _normalizeArabic(raw);
    final normCityAr = _normalizeArabic(cityAr.toLowerCase());
    final normNameAr = _normalizeArabic(nameAr.toLowerCase());
    final normCountryAr = _normalizeArabic(countryAr.toLowerCase());

    return code.toLowerCase().contains(raw) ||
        city.toLowerCase().contains(raw) ||
        name.toLowerCase().contains(raw) ||
        country.toLowerCase().contains(raw) ||
        normCityAr.contains(normQuery) ||
        normNameAr.contains(normQuery) ||
        normCountryAr.contains(normQuery);
  }
}

